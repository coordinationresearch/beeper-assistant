// ba mind against a made-up corpus and Mind map file. Nothing here is real.
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const BA = join(dirname(fileURLToPath(import.meta.url)), '..', 'scripts', 'ba.mjs');

function setup({ map = true } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'ba-mind-'));
  const file = join(dir, 'corpus.db');
  execFileSync('/usr/bin/sqlite3', [file, `
    CREATE TABLE schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL);
    INSERT INTO schema_migrations VALUES ('corpus-0003-review-fixes', '2026-09-30');
    CREATE TABLE corpus_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
    INSERT INTO corpus_meta VALUES ('built_at', '2026-10-01T00:00:00Z');
    CREATE TABLE chats (chat_key TEXT PRIMARY KEY, source TEXT, network TEXT, account TEXT, kind TEXT, title TEXT, counterparty TEXT, merged_into TEXT, beeper_chat_id TEXT, seen_at TEXT);
    CREATE TABLE person_members (member_key TEXT PRIMARY KEY, person_id TEXT NOT NULL);
    CREATE TABLE people (person_id TEXT PRIMARY KEY, display_name TEXT, name_source TEXT, state TEXT, created_at TEXT, updated_at TEXT);
    CREATE TABLE messages (message_key TEXT PRIMARY KEY, chat_key TEXT, sender TEXT, from_owner INTEGER, sent_at INTEGER, kind TEXT, text TEXT, retracted INTEGER DEFAULT 0, duplicate_of TEXT, source_state TEXT DEFAULT 'present');
    INSERT INTO chats VALUES ('!dana:beeper.local', 'beeper', 'whatsapp', 'x', 'single', 'Dana Example', 'beeper:wa:@dana', NULL, NULL, '');
    INSERT INTO person_members VALUES ('beeper:wa:@dana', 'p_dana');
    INSERT INTO people VALUES ('p_dana', 'Dana Example', 'contacts', 'ok', '', '');
    INSERT INTO messages VALUES ('beeper:$m1', '!dana:beeper.local', NULL, 1, ${Date.parse('2026-09-12T18:00:00Z')}, 'text', 'fired the new kiln twice this week', 0, NULL, 'present');
    INSERT INTO messages VALUES ('beeper:$m2', '!dana:beeper.local', NULL, 1, ${Date.parse('2026-09-13T18:00:00Z')}, 'text', 'oops', 1, NULL, 'present');
    INSERT INTO messages VALUES ('beeper:$m3', '!dana:beeper.local', NULL, 1, ${Date.parse('2026-09-14T18:00:00Z')}, 'text', 'a twin', 0, 'beeper:$m1', 'present');
    INSERT INTO messages VALUES ('beeper:$m4', '!dana:beeper.local', NULL, 1, ${Date.parse('2026-09-15T18:00:00Z')}, 'text', 'gone at the source', 0, NULL, 'gone');
  `]);
  if (map) writeFileSync(join(dir, 'mind-map.md'), '# Mind map\n\n## Pottery · 100% lately · 1 claim\n- 2026-09-12 · did · Fired the new kiln twice this week · beeper:$m1\n');
  const run = (...args) => spawnSync(process.execPath, [BA, 'mind', ...args], { encoding: 'utf8', env: { ...process.env, BEEPER_ASSISTANT_CORPUS: file, BEEPER_ASSISTANT_MODE: 'readonly' } });
  return { dir, run };
}

test('mind prints the file the Beeper Companion wrote, and where it is', () => {
  const { dir, run } = setup();
  const r = run();
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, new RegExp(`Mind map: ${join(dir, 'mind-map.md').replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`));
  assert.match(r.stdout, /Fired the new kiln twice this week · beeper:\$m1/);
});

// An invented map: one Area with seven claims, one with two, and two claims on no Area.
const BIG = ['# Mind map', '', 'Generated by Beeper Companion.', '', 'How to read it:', '- An Area or Interest title is a label.', '',
  '## Pottery · 70% lately · 7 claims', 'Claims by month, 2026-03 to 2026-09: 0 1 1 1 1 1 2', 'Interests: Glazes',
  ...[9, 8, 7, 6, 5, 4, 3].map((d, i) => `- 2026-0${d}-10 · did · Pottery claim ${i + 1} · beeper:$p${i}`),
  '', '## Sailing · 30% lately · 2 claims', 'Claims by month, 2026-03 to 2026-09: 1 0 0 0 0 0 1',
  '- 2026-09-02 · view · Thinks night sails beat day sails · beeper:$s1', '- 2026-03-02 · did · Crewed the spring regatta · beeper:$s2',
  '', '## Not on an Area yet', '- 2026-08-01 · topic · Talked about chess · beeper:$c1', '- 2026-07-01 · topic · Talked about tea · beeper:$c2', ''].join('\n');

test('mind prints a summary by default: each Area with its newest claims, and how to see the rest', () => {
  const { dir, run } = setup();
  writeFileSync(join(dir, 'mind-map.md'), BIG);
  const out = run().stdout;
  assert.match(out, /How to read it:/);
  assert.match(out, /## Pottery · 70% lately · 7 claims\nClaims by month, 2026-03 to 2026-09: 0 1 1 1 1 1 2\nInterests: Glazes\n/);
  assert.match(out, /Pottery claim 5 · beeper:\$p4\n… 2 more: ba mind --area 'Pottery'/);
  assert.ok(!out.includes('Pottery claim 6'));
  assert.match(out, /Crewed the spring regatta/);
  assert.match(out, /## Not on an Area yet\n2 claims on no Area yet\. ba mind --area 'Not on an Area yet' lists them\./);
  assert.ok(!out.includes('Talked about chess'));
});

test('mind --area, --since, and --grep print every claim that matches; --all prints the file', () => {
  const { dir, run } = setup();
  writeFileSync(join(dir, 'mind-map.md'), BIG);
  const area = run('--area', 'pott').stdout;
  assert.match(area, /Pottery claim 7/);
  assert.ok(!area.includes('Sailing'));
  const since = run('--since', '2026-08').stdout;
  assert.match(since, /Pottery claim 2 ·/);
  assert.ok(!since.includes('Pottery claim 3 ·') && !since.includes('regatta'));
  assert.match(since, /Talked about chess/);
  const grep = run('--grep', 'NIGHT SAILS').stdout;
  assert.match(grep, /## Sailing[^\n]*\n[^\n]*\n- 2026-09-02 · view · Thinks night sails/);
  assert.ok(!grep.includes('Pottery'));
  assert.match(run('--grep', 'nothing like this').stdout, /No claims match\./);
  assert.equal(run('--all').stdout, `Mind map: ${join(dir, 'mind-map.md')}\n\n${BIG}\n`);
});

test('mind reads the Talked about headings: --area and its hints use the title alone', () => {
  const { dir, run } = setup();
  const rule = 'What the Owner talks about, not where they work, what they belong to, or what they are.';
  const lines = (n) => Array.from({ length: n }, (_, i) => `- 2026-09-0${i + 1} · did · Glaze claim ${i} · beeper:$g${i}`);
  writeFileSync(join(dir, 'mind-map.md'), ['# Mind map', '', '## Talked about: Brightwater Studio · 100% lately · 6 claims', rule, ...lines(6), ''].join('\n'));
  const out = run().stdout;
  assert.match(out, /## Talked about: Brightwater Studio[^\n]*\nWhat the Owner talks about/);
  assert.match(out, /… 1 more: ba mind --area 'Brightwater Studio'/);
  assert.match(run('--area', 'Brightwater Studio').stdout, /Glaze claim 5/);
});

test('mind --area takes a whole title as given, and its hints quote titles safely', () => {
  const { dir, run } = setup();
  const claims = (t, n) => Array.from({ length: n }, (_, i) => `- 2026-09-0${i + 1} · did · ${t} claim ${i} · beeper:$${t[0]}${i}`);
  writeFileSync(join(dir, 'mind-map.md'), ['# Mind map', '', "## Bob's $(touch x) · 60% lately · 6 claims", ...claims('Bob', 6),
    '', '## Running · 20% lately · 1 claim', ...claims('Running', 1), '', '## Trail running (an Interest) · 20% lately · 1 claim', ...claims('Trail', 1), ''].join('\n'));
  const exact = run('--area', 'running').stdout;
  assert.match(exact, /Running claim 0/);
  assert.ok(!exact.includes('Trail'), 'a whole title matches only itself');
  assert.match(run('--area', 'runn').stdout, /Trail claim 0/, 'part of a title matches every title holding it');
  assert.match(run().stdout, /… 1 more: ba mind --area 'Bob'\\''s \$\(touch x\)'/);
  assert.match(run('--area', "Bob's $(touch x)").stdout, /Bob claim 5/, 'the quoted hint finds its Area');
});

test('mind says so when there is no Mind map yet', () => {
  const r = setup({ map: false }).run();
  assert.equal(r.status, 2);
  assert.match(r.stderr, /no Mind map on this Mac yet/);
});

test('--receipt reads the message a claim cites, as data', () => {
  const { run } = setup();
  const r = run('--receipt', 'beeper:$m1');
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /The Owner wrote this in a chat with Dana Example on WhatsApp/);
  assert.match(r.stdout, /«fired the new kiln twice this week»/);
  const j = JSON.parse(run('--receipt', 'beeper:$m1', '--json').stdout);
  assert.deepEqual([j.fromOwner, j.text], [true, 'fired the new kiln twice this week']);
});

test('--receipt refuses a message that is gone or retracted', () => {
  const { run } = setup();
  for (const key of ['beeper:$m2', 'beeper:$m3', 'beeper:$m4', 'beeper:$nope']) {
    const r = run('--receipt', key);
    assert.equal(r.status, 2);
    assert.match(r.stderr, /no longer has that message/);
  }
});

test('mind --area finds a title the Owner gave that holds " · " itself', () => {
  const { dir, run } = setup();
  const rule = 'What the Owner talks about, not where they work, what they belong to, or what they are.';
  writeFileSync(join(dir, 'mind-map.md'), ['# Mind map', '', '## Talked about: Clay · Glaze · 100% lately · 1 claim', rule, '- 2026-09-01 · did · Mixed a new glaze · beeper:$g1', ''].join('\n'));
  assert.match(run('--area', 'Clay · Glaze').stdout, /Mixed a new glaze/);
});
